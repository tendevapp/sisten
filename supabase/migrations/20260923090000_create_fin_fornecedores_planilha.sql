-- =====================================================================
-- Lista de fornecedores do controle orcamentario (planilha do Financeiro),
-- usada na exportacao "Fornecedores x ZL0136 mes a mes" em /admin/exportar.
--
-- A planilha nomeia fornecedores em texto livre (nomes cortados em 30
-- caracteres pelo SAP, anotacoes como "- Gas liquefeito", linhas que juntam
-- mais de um fornecedor como "CLINICAS (AUDIOCLIN / LAPEC / ...)"). O vinculo
-- com o SAP fica em fornecedor_codigos (array: uma linha pode somar varios
-- codigos). Linhas de lancamento financeiro (juros, emprestimos, tarifas,
-- caixinha) nao tem NF e ficam com tipo 'lancamento_sem_nf'.
-- =====================================================================

create table if not exists public.fin_fornecedores_planilha (
  id uuid primary key default gen_random_uuid(),
  secao text not null,
  ordem integer not null,
  nome_planilha text not null,
  tipo text not null default 'fornecedor' check (tipo in ('fornecedor', 'lancamento_sem_nf')),
  fornecedor_codigos text[] not null default '{}',
  observacao text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (secao, ordem)
);

drop trigger if exists tr_fin_fornecedores_planilha_updated_at on public.fin_fornecedores_planilha;
create trigger tr_fin_fornecedores_planilha_updated_at
  before update on public.fin_fornecedores_planilha
  for each row execute function public.tocar_updated_at();

alter table public.fin_fornecedores_planilha enable row level security;

drop policy if exists "fin_fornecedores_planilha_select" on public.fin_fornecedores_planilha;
create policy "fin_fornecedores_planilha_select"
  on public.fin_fornecedores_planilha for select to authenticated using (true);

drop policy if exists "fin_fornecedores_planilha_write" on public.fin_fornecedores_planilha;
create policy "fin_fornecedores_planilha_write"
  on public.fin_fornecedores_planilha for all to authenticated using (true) with check (true);

grant select, insert, update, delete on public.fin_fornecedores_planilha to authenticated;
revoke all on public.fin_fornecedores_planilha from anon;

