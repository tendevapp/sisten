-- Controle de Estoque do Almoxarifado
--
-- Reproduz a faixa operacional da planilha sem duplicar as bases SAP.
-- O cálculo final permanece no frontend (src/lib/controleEstoque.ts); esta
-- migration entrega fatos agregados, parâmetros auditados e rastreabilidade.

create table public.almox_controle_estoque_config (
  id uuid primary key default gen_random_uuid(),
  centro text not null,
  janela_inicio date not null,
  janela_fim date,
  lead_time_padrao_dias numeric not null default 15,
  intervalo_compra_dias numeric not null default 30,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by text,
  updated_by text,
  constraint almox_controle_config_centro_chk check (btrim(centro) <> ''),
  constraint almox_controle_config_janela_chk check (janela_fim is null or janela_fim >= janela_inicio),
  constraint almox_controle_config_lead_chk check (lead_time_padrao_dias >= 0),
  constraint almox_controle_config_intervalo_chk check (intervalo_compra_dias >= 0)
);

comment on table public.almox_controle_estoque_config is
  'Parâmetros globais auditados da faixa operacional de estoque por centro.';

create unique index almox_controle_config_centro_ativo_uidx
  on public.almox_controle_estoque_config (centro)
  where ativo;
create index almox_controle_config_centro_idx
  on public.almox_controle_estoque_config (centro);
create index almox_controle_config_ativo_idx
  on public.almox_controle_estoque_config (ativo);

create table public.almox_controle_estoque_override (
  id uuid primary key default gen_random_uuid(),
  material text not null,
  centro text not null,
  tipo_gestao text,
  lead_time_dias numeric,
  intervalo_compra_dias numeric,
  estoque_minimo numeric,
  estoque_maximo numeric,
  quantidade_por_torre numeric,
  justificativa text not null,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by text,
  updated_by text,
  constraint almox_controle_override_material_chk check (btrim(material) <> ''),
  constraint almox_controle_override_centro_chk check (btrim(centro) <> ''),
  constraint almox_controle_override_lead_chk check (lead_time_dias is null or lead_time_dias >= 0),
  constraint almox_controle_override_intervalo_chk check (intervalo_compra_dias is null or intervalo_compra_dias >= 0),
  constraint almox_controle_override_minimo_chk check (estoque_minimo is null or estoque_minimo >= 0),
  constraint almox_controle_override_maximo_chk check (estoque_maximo is null or estoque_maximo >= 0),
  constraint almox_controle_override_faixa_chk check (
    estoque_minimo is null or estoque_maximo is null or estoque_maximo >= estoque_minimo
  ),
  constraint almox_controle_override_torre_chk check (
    quantidade_por_torre is null or quantidade_por_torre > 0
  ),
  constraint almox_controle_override_justificativa_chk check (
    not ativo or length(btrim(justificativa)) >= 5
  )
);

comment on table public.almox_controle_estoque_override is
  'Exceções por material/centro. Registros são inativados, nunca excluídos pela aplicação.';

create unique index almox_controle_override_material_centro_ativo_uidx
  on public.almox_controle_estoque_override (material, centro)
  where ativo;
create index almox_controle_override_material_idx
  on public.almox_controle_estoque_override (material);
create index almox_controle_override_centro_idx
  on public.almox_controle_estoque_override (centro);
create index almox_controle_override_ativo_idx
  on public.almox_controle_estoque_override (ativo);

create table public.almox_controle_estoque_auditoria (
  id bigint generated by default as identity primary key,
  entidade text not null,
  registro_id uuid not null,
  acao text not null,
  dados_anteriores jsonb,
  dados_novos jsonb,
  alterado_por text,
