  ),
  constraint almox_controle_auditoria_acao_chk check (acao in ('INSERT', 'UPDATE'))
);

comment on table public.almox_controle_estoque_auditoria is
  'Histórico imutável de parâmetros e overrides do Controle de Estoque.';

create index almox_controle_auditoria_registro_idx
