create or replace function public.auditar_almox_controle_estoque()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_anterior jsonb;
  v_novo jsonb;
  v_registro_id uuid;
  v_alterado_por text;
begin
  if tg_op = 'INSERT' then
    v_anterior := null;
    v_novo := to_jsonb(new);
    v_registro_id := new.id;
  else
    v_anterior := to_jsonb(old);
    v_novo := to_jsonb(new);
    v_registro_id := new.id;
  end if;

  v_alterado_por := coalesce(
    v_novo ->> 'updated_by',
    v_novo ->> 'created_by',
    auth.uid()::text
  );

  insert into public.almox_controle_estoque_auditoria (
    entidade,
    registro_id,
    acao,
    dados_anteriores,
    dados_novos,
    alterado_por
  ) values (
    tg_table_name,
    v_registro_id,
    tg_op,
    v_anterior,
    v_novo,
    v_alterado_por
  );

  return new;
end;
$$;

revoke all on function public.auditar_almox_controle_estoque() from public, anon, authenticated;

